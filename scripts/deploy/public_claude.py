#!/usr/bin/env python3
"""Public Claude — one command to run it on a server (docs/deploy/public-claude.md).

    python3 scripts/deploy/public_claude.py up        # first run creates .env.public-claude
    python3 scripts/deploy/public_claude.py status    # health, seats, RAM/CPU per runtime
    python3 scripts/deploy/public_claude.py logs      # per-answer log lines of the runtimes
    python3 scripts/deploy/public_claude.py down      # Core keeps running

Pool size = CLAUDE_RT_POOL in .env.public-claude (1-9, default 2). The base file
docker-compose.public-claude.yml declares runtimes 1-2; for a bigger pool this writes
docker-compose.public-claude.pool.yml (runtimes 3..N + public-mcp's list), gitignored.
nginx needs no change for any pool size up to 9 (its index class is [1-9]).

Stdlib only; needs docker compose v2 and python3 on the host.
"""
from __future__ import annotations

import base64
import json
import os
import secrets
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENV = ROOT / ".env.public-claude"
BASE = ROOT / "docker-compose.public-claude.yml"
POOL = ROOT / "docker-compose.public-claude.pool.yml"
PROJECT = "appbi-public-claude"
MAX_POOL = 9


def read_env() -> dict:
    out: dict = {}
    if ENV.exists():
        for line in ENV.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def ensure_env() -> dict:
    """Create .env.public-claude on the first run (random keys, 0600), and add a secret for
    every runtime the pool size asks for. Existing values are never changed."""
    env = read_env()
    lines = ENV.read_text(encoding="utf-8").splitlines() if ENV.exists() else [
        "# Public Claude — created by scripts/deploy/public_claude.py. Never commit this file.",
        "# APPBI_PUBLIC_HOST: the app's host as viewers open it (no scheme, no slash).",
    ]
    added = []

    def put(key: str, value: str) -> None:
        if not env.get(key):
            env[key] = value
            lines.append(f"{key}={value}")
            added.append(key)

    if not env.get("APPBI_PUBLIC_HOST"):
        host = os.environ.get("APPBI_PUBLIC_HOST", "").strip() or (
            input("APPBI_PUBLIC_HOST (e.g. report.example.com): ").strip() if sys.stdin.isatty() else "")
        if not host:
            sys.exit("set APPBI_PUBLIC_HOST in .env.public-claude (the app's public host) and run again")
        put("APPBI_PUBLIC_HOST", host)
    put("CLAUDE_RT_POOL", os.environ.get("CLAUDE_RT_POOL", "").strip() or "2")
    put("PUBLIC_MCP_STATE_KEY", base64.urlsafe_b64encode(os.urandom(32)).decode())
    for i in range(1, max(2, pool_size(env)) + 1):  # the base file always declares 2
        put(f"CLAUDE_RT_SECRET_{i}", secrets.token_urlsafe(32))
    if added:
        ENV.write_text("\n".join(lines) + "\n", encoding="utf-8")
        try:
            os.chmod(ENV, 0o600)
        except OSError:
            pass
        print(f"{ENV.name}: added {', '.join(added)}")
    return env


def pool_size(env: dict) -> int:
    try:
        n = int(env.get("CLAUDE_RT_POOL") or 2)
    except ValueError:
        sys.exit("CLAUDE_RT_POOL must be a number (1-9)")
    if not 1 <= n <= MAX_POOL:
        sys.exit(f"CLAUDE_RT_POOL must be 1-{MAX_POOL}")
    return n


def runtime_block(i: int) -> str:
    return f"""  claude-rt-{i}:
    image: appbi-claude-runtime:${{GIT_SHA:-local}}
    pull_policy: never
    depends_on: [ claude-rt-1 ]
    restart: always
    read_only: true
    tmpfs:
      - /home/viewer:uid=1001,gid=1001,mode=0700,size=256m
      - /tmp:size=64m
    mem_limit: ${{CLAUDE_RT_MEM:-768m}}
    cpus: ${{CLAUDE_RT_CPUS:-1.0}}
    pids_limit: 256
    security_opt: [ "no-new-privileges:true" ]
    cap_drop: [ ALL ]
    extra_hosts: [ "${{APPBI_PUBLIC_HOST}}:host-gateway" ]
    logging: {{ driver: json-file, options: {{ max-size: "10m", max-file: "3" }} }}
    environment:
      RUNTIME_INDEX: "{i}"
      RUNTIME_SECRET: ${{CLAUDE_RT_SECRET_{i}:?set CLAUDE_RT_SECRET_{i}}}
      PUBLIC_MCP_INTERNAL: http://public-mcp:8091
    ports: [ "127.0.0.1:810{i}:8099" ]
    networks: [ rtnet{i} ]
"""


def write_pool_file(n: int) -> list:
    """Compose files for this pool size. 1-2 runtimes: the base file (runtime 2 is simply not
    used by public-mcp when n == 1); more: base + a generated override."""
    files = [BASE]
    if n <= 2:
        if POOL.exists():
            POOL.unlink()
        return files
    urls = ",".join(f"http://claude-rt-{i}:8099" for i in range(1, n + 1))
    secrets_ = ",".join(f"${{CLAUDE_RT_SECRET_{i}}}" for i in range(1, n + 1))
    body = ["# GENERATED by scripts/deploy/public_claude.py for CLAUDE_RT_POOL=%d. Do not edit." % n,
            f"name: {PROJECT}", "services:", "  public-mcp:", "    environment:",
            f"      PUBLIC_MCP_RUNTIMES: {urls}", f"      PUBLIC_MCP_RUNTIME_SECRET: {secrets_}",
            "    networks: [ " + ", ".join(f"rtnet{i}" for i in range(3, n + 1)) + " ]"]
    body += [runtime_block(i).rstrip("\n") for i in range(3, n + 1)]
    body += ["networks:"] + [f"  rtnet{i}:\n    name: {PROJECT}-rt{i}" for i in range(3, n + 1)]
    POOL.write_text("\n".join(body) + "\n", encoding="utf-8")
    files.append(POOL)
    return files


def compose(files: list, *args: str, env_extra: dict | None = None) -> int:
    cmd = ["docker", "compose", "-p", PROJECT, "--env-file", str(ENV)]
    for f in files:
        cmd += ["-f", str(f)]
    cmd += list(args)
    e = {**os.environ, **(env_extra or {})}
    return subprocess.call(cmd, cwd=ROOT, env=e)


def git_sha() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short=8", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:  # noqa: BLE001
        return "local"


def healthz(timeout: float = 3) -> bool:
    try:
        port = read_env().get("PUBLIC_MCP_PORT") or "8091"
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/public-mcp/healthz", timeout=timeout) as r:
            return r.status == 200
    except Exception:  # noqa: BLE001
        return False


def cmd_up() -> int:
    env = ensure_env()
    n = pool_size(env)
    files = write_pool_file(n)
    sha = env.get("GIT_SHA") or git_sha()
    extra = {"GIT_SHA": sha}
    if n == 1:  # public-mcp offers only runtime 1
        extra.update(PUBLIC_MCP_RUNTIMES="http://claude-rt-1:8099")
    print(f"Public Claude: {n} runtime(s), image tag {sha}")
    rc = compose(files, "up", "-d", "--build", "--remove-orphans", env_extra=extra)
    if rc:
        return rc
    import time
    for _ in range(30):
        if healthz():
            break
        time.sleep(2)
    return cmd_status()


def cmd_status() -> int:
    env = read_env()
    n = pool_size(env) if env else 0
    ok = healthz()
    print(f"public-mcp healthz: {'ok' if ok else 'NOT OK'}")
    for i in range(1, n + 1):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:810{i}/health", timeout=3) as r:
                h = json.loads(r.read())
            print(f"  runtime {i}: {'in use' if h.get('state') == 'leased' else 'free'}")
        except Exception:  # noqa: BLE001
            print(f"  runtime {i}: NOT REACHABLE")
    subprocess.call(["docker", "stats", "--no-stream", "--format", "  {{.Name}}  CPU {{.CPUPerc}}  RAM {{.MemUsage}}",
                     *[f"{PROJECT}-{s}-1" for s in ["public-mcp", *[f"claude-rt-{i}" for i in range(1, n + 1)]]]])
    print(f"Check from outside: curl -s https://{env.get('APPBI_PUBLIC_HOST', '<host>')}/public-mcp/healthz  "
          f"and  curl -o /dev/null -w '%{{http_code}}' https://{env.get('APPBI_PUBLIC_HOST', '<host>')}/claude-rt/1/api/status  (expect 403)")
    return 0 if ok else 1


def cmd_logs() -> int:
    env = read_env()
    n = pool_size(env)
    return compose(write_pool_file(n), "logs", "--tail", "200", *[f"claude-rt-{i}" for i in range(1, n + 1)])


def cmd_down() -> int:
    env = read_env()
    return compose(write_pool_file(pool_size(env)) if env else [BASE], "down")


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "status"
    fn = {"up": cmd_up, "status": cmd_status, "logs": cmd_logs, "down": cmd_down}.get(action)
    if fn is None:
        sys.exit(__doc__)
    sys.exit(fn())
